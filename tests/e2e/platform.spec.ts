test('save downloads encrypted content; incorrect import never replaces the active plan', async ({ page }) => {
  await personal(page)
  await nav(page, 'Save & resume').click()
  await page.getByLabel('Create a file passphrase').fill('made up test phrase only')
  await page.getByLabel('Repeat the file passphrase').fill('made up test phrase only')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download private plan' }).click()
  const download = await downloadPromise
  const encrypted = fs.readFileSync((await download.path())!, 'utf8')
  expect(encrypted).not.toContain('recovery')
  expect(encrypted).not.toContain('made up test phrase only')
  expect(JSON.parse(encrypted).cipher).toBe('AES-GCM')
  await expect(page.getByLabel('Create a file passphrase')).toHaveValue('')
  const fixture = await encryptPlan(examplePlan(), 'example import passphrase')
  await page.getByLabel('Your .untangle file').setInputFiles({ name: 'example.untangle', mimeType: 'application/json', buffer: Buffer.from(fixture) })
  await page.getByLabel('Its file passphrase').fill('incorrect')
  await page.getByRole('button', { name: 'Open private plan' }).click()
  await expect(page.getByRole('alert')).toContainText('Could not open')
  await expect(nav(page, 'My plan 5')).toBeVisible()
  await page.getByLabel('Its file passphrase').fill('example import passphrase')
  await page.getByRole('button', { name: 'Open private plan' }).click()
  await expect(page.getByRole('heading', { name: 'Ready to open a fictional example' })).toBeVisible()
  await page.getByRole('button', { name: 'Use this saved plan' }).click()
  await expect(page.locator('.p-example-banner')).toBeVisible()
  await expect(page.locator('.p-task-list')).toContainText('Still a question')
  await expect(page.locator('.p-progress-count')).toContainText('1 / 9')
})

