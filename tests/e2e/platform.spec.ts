test('responsive home, plan and guide pass accessibility checks', async ({ page }) => {
  test.setTimeout(120000)
  const audits: unknown[] = []
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/?view=plan')
    const startBox = await page.getByRole('button', { name: 'Make my own plan', exact: true }).boundingBox()
    expect(startBox!.y + startBox!.height).toBeLessThan(1000)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    audits.push({ width, page: 'home', violations: result.violations }); expect(result.violations).toEqual([])
    if (width === 390 || width === 1440) await capture(page, `home-${width}`)
    await page.getByRole('button', { name: width <= 1100 ? 'Explore an example plan' : 'Explore Maya’s example plan' }).click()
    await expect(page.locator('.p-example-banner')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (width === 390 || width === 1440) await capture(page, `plan-${width}`)
    const planAudit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    audits.push({ width, page: 'plan', violations: planAudit.violations }); expect(planAudit.violations).toEqual([])
    await page.getByRole('button', { name: /Look at devices using your Google account Google/ }).click()
    await page.getByRole('button', { name: /Before a change/ }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (width === 390 || width === 1440) await capture(page, `guide-${width}`)
    const guideAudit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    audits.push({ width, page: 'guide', violations: guideAudit.violations }); expect(guideAudit.violations).toEqual([])
  }
  fs.writeFileSync('docs/platform-accessibility-audit.json', JSON.stringify(audits, null, 2))
})
